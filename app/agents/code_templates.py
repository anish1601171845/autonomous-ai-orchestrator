"""Deterministic code generation templates used by the Coding Agent when no LLM is configured.

Each template yields a working module plus a pytest suite. They are intentionally generic but real:
no stubs, no hard-coded passes.
"""
from __future__ import annotations

import re

AUTH_WORDS = ["login", "registration", "register", "auth", "sign up", "signup", "sign in", "password", "account"]
DB_WORDS = ["database", "schema", "repository", "persistence", "storage"]
DASH_WORDS = ["dashboard", "report", "analytics", "summary", "statistics", "metrics", "kpi"]
SETUP_WORDS = ["set up project", "setup", "configuration", "dependency management"]


def module_name(feature: str, description: str) -> str:
    d = description.lower()
    if feature == "project":
        if any(w in d for w in SETUP_WORDS):
            return "project_config"
        if any(w in d for w in DB_WORDS):
            return "database"
    name = re.sub(r"[^a-z0-9]+", "_", feature.lower()).strip("_") or "service"
    return ("m_" + name) if name[0].isdigit() else name


def archetype(feature: str, description: str) -> str:
    t = f"{feature} {description}".lower()
    if feature == "project" and any(w in t for w in SETUP_WORDS):
        return "config"
    if feature == "project" and any(w in t for w in DB_WORDS):
        return "database"
    if any(w in t for w in AUTH_WORDS):
        return "auth"
    if any(w in t for w in DASH_WORDS):
        return "dashboard"
    if any(w in t for w in DB_WORDS):
        return "database"
    return "crud"


def _entity(feature: str) -> str:
    words = [w for w in re.findall(r"[a-z]+", feature.lower()) if w not in {"management", "service", "module", "system", "the", "and"}]
    base = words[-1] if words else "item"
    return base.rstrip("s") if len(base) > 3 else base


def _cls(s: str) -> str:
    return "".join(p.capitalize() for p in re.findall(r"[a-z0-9]+", s.lower())) or "Item"


def render(kind: str, mod: str, feature: str, title: str) -> tuple[str, str]:
    header = f'"""{title}.\n\nGenerated by coding_agent (template backend) for feature: {feature}.\n"""\n'
    if kind == "auth":
        return header + AUTH_MODULE, AUTH_TESTS.replace("{mod}", mod)
    if kind == "database":
        return header + DB_MODULE, DB_TESTS.replace("{mod}", mod)
    if kind == "dashboard":
        return header + DASH_MODULE, DASH_TESTS.replace("{mod}", mod)
    if kind == "config":
        return header + CONFIG_MODULE, CONFIG_TESTS.replace("{mod}", mod)
    ent = _entity(feature)
    cls = _cls(ent)
    return header + CRUD_MODULE.replace("{Cls}", cls).replace("{ent}", ent), CRUD_TESTS.replace("{mod}", mod).replace("{Cls}", cls)


AUTH_MODULE = '''from __future__ import annotations

import hashlib
import hmac
import re
import secrets
from dataclasses import dataclass

EMAIL_RE = re.compile(r"^[^@\\s]+@[^@\\s]+\\.[A-Za-z]{2,}$")
USERNAME_RE = re.compile(r"^[A-Za-z0-9_.-]{3,32}$")


class AuthError(ValueError):
    """Raised for invalid registration or authentication attempts."""


@dataclass(frozen=True)
class User:
    username: str
    email: str
    password_hash: str
    salt: str


class UserService:
    """In-memory user registry with PBKDF2 password hashing and opaque session tokens."""

    def __init__(self, iterations: int = 100_000) -> None:
        self._iterations = iterations
        self._users: dict[str, User] = {}
        self._sessions: dict[str, str] = {}

    @staticmethod
    def validate_password(password: str) -> None:
        if len(password) < 8:
            raise AuthError("password must be at least 8 characters")
        if not re.search(r"[A-Za-z]", password) or not re.search(r"\\d", password):
            raise AuthError("password must contain letters and digits")

    def _hash(self, password: str, salt: str) -> str:
        return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), self._iterations).hex()

    def register(self, username: str, email: str, password: str) -> User:
        if not USERNAME_RE.match(username or ""):
            raise AuthError("username must be 3-32 characters of letters, digits, _ . -")
        if not EMAIL_RE.match(email or ""):
            raise AuthError("invalid email address")
        key = username.lower()
        if key in self._users or any(u.email.lower() == email.lower() for u in self._users.values()):
            raise AuthError("username or email already registered")
        self.validate_password(password)
        salt = secrets.token_hex(16)
        user = User(username, email, self._hash(password, salt), salt)
        self._users[key] = user
        return user

    def authenticate(self, username: str, password: str) -> str:
        user = self._users.get((username or "").lower())
        if user is None or not hmac.compare_digest(user.password_hash, self._hash(password, user.salt)):
            raise AuthError("invalid username or password")
        token = secrets.token_urlsafe(32)
        self._sessions[token] = user.username.lower()
        return token

    def user_for_token(self, token: str) -> User:
        key = self._sessions.get(token)
        if key is None:
            raise AuthError("invalid or expired session")
        return self._users[key]

    def logout(self, token: str) -> None:
        self._sessions.pop(token, None)

    def count(self) -> int:
        return len(self._users)
'''

