CONFIG_MODULE = '''from __future__ import annotations

from dataclasses import dataclass, fields
from typing import Mapping


@dataclass(frozen=True)
class AppConfig:
    app_name: str = "application"
    environment: str = "development"
    debug: bool = False
    port: int = 8000
    database_url: str = "sqlite:///app.db"

    def __post_init__(self) -> None:
        if self.environment not in {"development", "staging", "production"}:
            raise ValueError(f"unknown environment: {self.environment}")
        if not 1 <= self.port <= 65535:
            raise ValueError("port must be between 1 and 65535")
        if self.environment == "production" and self.debug:
            raise ValueError("debug must be disabled in production")


def _coerce(raw: str, typ: type):
    if typ is bool:
        if raw.strip().lower() in {"1", "true", "yes", "on"}:
            return True
        if raw.strip().lower() in {"0", "false", "no", "off"}:
            return False
        raise ValueError(f"not a boolean: {raw!r}")
    return typ(raw)


def load_config(env: Mapping[str, str], prefix: str = "APP_") -> AppConfig:
    """Build configuration from an environment-style mapping (e.g. os.environ)."""
    values = {}
    types = {"app_name": str, "environment": str, "debug": bool, "port": int, "database_url": str}
    for f in fields(AppConfig):
        key = prefix + f.name.upper()
        if key in env:
            values[f.name] = _coerce(env[key], types[f.name])
    return AppConfig(**values)
'''

