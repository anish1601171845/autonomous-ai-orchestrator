DASH_MODULE = '''from __future__ import annotations

from collections import Counter
from statistics import mean, median
from typing import Any, Iterable


def _values(records: Iterable[dict[str, Any]], field: str) -> list[float]:
    out = []
    for r in records:
        v = r.get(field)
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            out.append(float(v))
    return out


def kpis(records: list[dict[str, Any]], value_field: str) -> dict[str, float | int]:
    """Headline numbers for a dashboard card row."""
    vals = _values(records, value_field)
    if not vals:
        return {"count": len(records), "valid": 0, "total": 0.0, "mean": 0.0, "median": 0.0, "min": 0.0, "max": 0.0}
    return {"count": len(records), "valid": len(vals), "total": round(sum(vals), 4), "mean": round(mean(vals), 4),
            "median": round(median(vals), 4), "min": min(vals), "max": max(vals)}


def group_counts(records: list[dict[str, Any]], key: str) -> dict[str, int]:
    return dict(Counter(str(r.get(key, "unknown")) for r in records).most_common())


def group_mean(records: list[dict[str, Any]], key: str, value_field: str) -> dict[str, float]:
    groups: dict[str, list[float]] = {}
    for r in records:
        v = r.get(value_field)
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            groups.setdefault(str(r.get(key, "unknown")), []).append(float(v))
    return {k: round(mean(v), 4) for k, v in sorted(groups.items())}


def top_n(records: list[dict[str, Any]], value_field: str, n: int = 5) -> list[dict[str, Any]]:
    if n < 0:
        raise ValueError("n must be non-negative")
    valid = [r for r in records if isinstance(r.get(value_field), (int, float))]
    return sorted(valid, key=lambda r: r[value_field], reverse=True)[:n]
'''

