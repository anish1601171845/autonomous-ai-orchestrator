CRUD_MODULE = '''from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any


class ValidationError(ValueError):
    """Raised when {ent} data is invalid."""


class NotFoundError(KeyError):
    """Raised when a {ent} does not exist."""


@dataclass
class {Cls}:
    id: int
    name: str
    attributes: dict[str, Any] = field(default_factory=dict)
    active: bool = True
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


class {Cls}Service:
    """Validated create/read/update/delete/search service for {ent} records."""

    def __init__(self) -> None:
        self._items: dict[int, {Cls}] = {}
        self._next_id = 1

    @staticmethod
    def _validate_name(name: str) -> str:
        if not isinstance(name, str) or not name.strip():
            raise ValidationError("name is required")
        if len(name) > 200:
            raise ValidationError("name must be at most 200 characters")
        return name.strip()

    def create(self, name: str, **attributes: Any) -> {Cls}:
        name = self._validate_name(name)
        if any(i.name.lower() == name.lower() for i in self._items.values()):
            raise ValidationError(f"{ent} '{name}' already exists")
        item = {Cls}(self._next_id, name, dict(attributes))
        self._items[item.id] = item
        self._next_id += 1
        return item

    def get(self, item_id: int) -> {Cls}:
        try:
            return self._items[item_id]
        except KeyError:
            raise NotFoundError(item_id) from None

    def update(self, item_id: int, name: str | None = None, **attributes: Any) -> {Cls}:
        item = self.get(item_id)
        if name is not None:
            item.name = self._validate_name(name)
        item.attributes.update(attributes)
        return item

    def deactivate(self, item_id: int) -> {Cls}:
        item = self.get(item_id)
        item.active = False
        return item

    def delete(self, item_id: int) -> None:
        self.get(item_id)
        del self._items[item_id]

    def list(self, active_only: bool = False) -> list[{Cls}]:
        return [i for i in self._items.values() if i.active or not active_only]

    def search(self, query: str) -> list[{Cls}]:
        q = (query or "").lower()
        return [i for i in self._items.values()
                if q in i.name.lower() or any(q in str(v).lower() for v in i.attributes.values())]
'''

