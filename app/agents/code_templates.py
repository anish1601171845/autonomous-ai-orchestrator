DB_MODULE = '''from __future__ import annotations

import re
import sqlite3
from typing import Any

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,63}$")
_TYPES = {"INTEGER", "TEXT", "REAL", "BLOB", "NUMERIC"}


def _ident(name: str) -> str:
    if not _IDENT.match(name or ""):
        raise ValueError(f"invalid identifier: {name!r}")
    return name


class Database:
    """Small SQLite repository with schema creation and parameterised CRUD."""

    def __init__(self, path: str = ":memory:") -> None:
        self.conn = sqlite3.connect(path)
        self.conn.row_factory = sqlite3.Row
        self.conn.execute("PRAGMA foreign_keys = ON")

    def create_table(self, table: str, columns: dict[str, str]) -> None:
        cols = []
        for col, typ in columns.items():
            base = typ.split()[0].upper()
            if base not in _TYPES:
                raise ValueError(f"unsupported column type: {typ}")
            cols.append(f"{_ident(col)} {typ}")
        self.conn.execute(f"CREATE TABLE IF NOT EXISTS {_ident(table)} (id INTEGER PRIMARY KEY AUTOINCREMENT, {', '.join(cols)})")
        self.conn.commit()

    def insert(self, table: str, row: dict[str, Any]) -> int:
        keys = [_ident(k) for k in row]
        cur = self.conn.execute(
            f"INSERT INTO {_ident(table)} ({', '.join(keys)}) VALUES ({', '.join('?' for _ in keys)})", list(row.values()))
        self.conn.commit()
        return int(cur.lastrowid)

    def get(self, table: str, row_id: int) -> dict[str, Any] | None:
        r = self.conn.execute(f"SELECT * FROM {_ident(table)} WHERE id = ?", (row_id,)).fetchone()
        return dict(r) if r else None

    def update(self, table: str, row_id: int, changes: dict[str, Any]) -> bool:
        if not changes:
            return False
        sets = ", ".join(f"{_ident(k)} = ?" for k in changes)
        cur = self.conn.execute(f"UPDATE {_ident(table)} SET {sets} WHERE id = ?", [*changes.values(), row_id])
        self.conn.commit()
        return cur.rowcount == 1

    def delete(self, table: str, row_id: int) -> bool:
        cur = self.conn.execute(f"DELETE FROM {_ident(table)} WHERE id = ?", (row_id,))
        self.conn.commit()
        return cur.rowcount == 1

    def list(self, table: str, **filters: Any) -> list[dict[str, Any]]:
        where = " AND ".join(f"{_ident(k)} = ?" for k in filters)
        sql = f"SELECT * FROM {_ident(table)}" + (f" WHERE {where}" if where else "") + " ORDER BY id"
        return [dict(r) for r in self.conn.execute(sql, list(filters.values()))]

    def close(self) -> None:
        self.conn.close()
'''

